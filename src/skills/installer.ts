import { mkdir } from "node:fs/promises";
import path from "node:path";
import type { ScaffoldConfig, SkillDefinition } from "../types";
import { getSkillsByRoles } from "./catalog";
import { renderSkillMarkdown } from "./templates-eng";

export interface SkillInstallSummary {
  totalSkills: number;
  customSkills: number;
  externalSkills: number;
  externalFetchedRepos: string[];
  installedSkillNames: string[];
}

export async function installProjectSkills(
  config: ScaffoldConfig,
  onProgress?: (status: string) => void,
): Promise<SkillInstallSummary> {
  const selectedSkills = getSkillsByRoles(config.roles);
  const skillsRoot = path.join(config.targetDir, ".agents", "skills");
  await mkdir(skillsRoot, { recursive: true });

  let customCount = 0;
  let externalCount = 0;
  const byRepo = new Map<string, SkillDefinition[]>();

  for (const skill of selectedSkills) {
    onProgress?.(skill.name);
    const skillDir = path.join(skillsRoot, skill.name);
    await mkdir(skillDir, { recursive: true });
    const markdown = renderSkillMarkdown(skill, config.scope);
    await Bun.write(path.join(skillDir, "SKILL.md"), markdown);

    if (skill.repo === "custom") {
      customCount++;
    } else {
      externalCount++;
      const list = byRepo.get(skill.repo) ?? [];
      list.push(skill);
      byRepo.set(skill.repo, list);
    }
  }

  const catalogMarkdown = buildSkillsIndexMarkdown(selectedSkills, config);
  await Bun.write(path.join(skillsRoot, "README.md"), catalogMarkdown);

  const externalFetchedRepos: string[] = [];
  if (config.fetchExternalSkills && byRepo.size > 0) {
    for (const [repo, repoSkills] of byRepo.entries()) {
      onProgress?.(`syncing ${repo}`);
      const skillArgs = repoSkills.flatMap((s) => ["--skill", s.name]);
      const ok = await runSkillsCliAdd(config.targetDir, repo, skillArgs);
      if (ok) {
        externalFetchedRepos.push(repo);
      }
    }
  }

  return {
    totalSkills: selectedSkills.length,
    customSkills: customCount,
    externalSkills: externalCount,
    externalFetchedRepos,
    installedSkillNames: selectedSkills.map((s) => s.name),
  };
}

async function runSkillsCliAdd(
  cwd: string,
  repo: string,
  skillArgs: string[],
): Promise<boolean> {
  try {
    const proc = Bun.spawn(["npx", "--yes", "skills", "add", repo, ...skillArgs, "--yes"], {
      cwd,
      stdout: "ignore",
      stderr: "ignore",
      stdin: "ignore",
    });

    const timeout = setTimeout(() => {
      try {
        proc.kill();
      } catch {
        // ignore
      }
    }, 30_000);

    const exitCode = await proc.exited;
    clearTimeout(timeout);
    return exitCode === 0;
  } catch {
    return false;
  }
}

function buildSkillsIndexMarkdown(
  skills: SkillDefinition[],
  config: ScaffoldConfig,
): string {
  const rows = skills
    .map((s) => `| \`${s.name}\` | \`${s.role.toUpperCase()}\` | \`${s.repo}\` | ${s.description} |`)
    .join("\n");

  return `# AI Agent Skills Catalog (\`${config.projectSlug}\`)

Generated by **best-stack** (\`bun run scaff\`). All skills are located in \`.agents/skills/<skill-name>/SKILL.md\`.

## Installed Skills (${skills.length})

| Skill | Role | Source | Description |
|---|---|---|---|
${rows}
`;
}
